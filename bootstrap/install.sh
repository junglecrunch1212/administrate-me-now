#!/bin/bash -p
set -Eeuo pipefail
unset BASH_ENV ENV CDPATH PYTHONHOME PYTHONPATH PYTHONSTARTUP PYTHONINSPECT PYTHONUSERBASE
unset ADMINME_BOOTSTRAP_SUPERVISED ADMINME_UPDATE_SUPERVISED
unset ADMINME_SUPERVISED_CANDIDATE_ROOT ADMINME_SUPERVISED_CANDIDATE_COMMIT
unset ADMINME_SUPERVISED_ACTIVE_RELEASE_ROOT ADMINME_FIXED_CONTROLLER_ROOT
unset ADMINME_CONTROLLER_RUNTIME_ROOT ADMINME_UPGRADE_OPERATION_LOCK_FD
unset ADMINME_UPGRADE_CONTROLLER_COMMIT ADMINME_UPGRADE_CONTROLLER_ROOT
unset ADMINME_PREPARATION_POETRY ADMINME_TEST_MODE ADMINME_SUPERVISOR_REPORT
export PATH="/usr/bin:/bin:/usr/sbin:/sbin:/opt/homebrew/bin"
script_path="${BASH_SOURCE[0]}"
script_parent="${script_path%/*}"
[[ "$script_parent" != "$script_path" ]] || script_parent="."
SCRIPT_DIR="$(cd "$script_parent" && pwd -P)"
exec "$SCRIPT_DIR/bootstrap-macos.sh" "$@"
