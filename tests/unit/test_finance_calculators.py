def values(model: str, **overrides: Any) -> dict[str, Any]:
    return calculate(model, "1", {**inputs()[model], **overrides})["values"]


def test_every_admitted_model_has_strict_schemas_and_numeric_receipts():
    catalog = calculator_catalog()
    assert set(catalog) == set(inputs())
    for model, body in inputs().items():
        item = catalog[model]
        assert item["input_schema"]["additionalProperties"] is False
        assert item["output_schema"]["additionalProperties"] is False
        assert item["implementation_state"] == "implemented"
        assert item["performance_class"] == "light"
        result = calculate(model, "1", body)
        assert result["readiness"] == "qualified"
        assert result["input_kind"] == "explicit_hypothetical"
        assert result["provider_effect_count"] == 0
        assert result["assumptions"] and result["exclusions"]
        assert len({m["metric_id"] for m in result["metrics"]}) == len(
            result["metrics"]
        )
        numeric = {key for key, value in result["values"].items() if type(value) is int}
        receipted = {m["metric_id"].split(":")[-1] for m in result["metrics"]}
        assert numeric <= receipted


