@pytest.mark.parametrize("model", sorted(inputs()))
def test_missing_currency_is_explicit_and_safe(model):
    body = inputs()[model]
    del body["currency"]
    with pytest.raises(CalculatorError) as caught:
        calculate(model, "1", body)
    assert caught.value.code == "missing_evidence"
    assert caught.value.missing_fields == ("currency",)


