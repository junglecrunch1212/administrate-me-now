def test_numeric_receipts_bind_to_normalized_inputs_and_model():
    body = inputs()["fixed_debt"]
    original = calculate("fixed_debt", "1", body)
    equivalent = deepcopy(body)
    equivalent["terms"]["annual_rate"] = "0.120000"
    del equivalent["terms"]["extra_monthly_principal_minor"]
    assert (
        calculate("fixed_debt", "1", equivalent)["result_id"] == original["result_id"]
    )
    changed = deepcopy(body)
    changed["terms"]["monthly_payment_minor"] += 1
    alternative = calculate("fixed_debt", "1", changed)
    assert alternative["result_id"] != original["result_id"]
    assert {m["metric_id"] for m in original["metrics"]}.isdisjoint(
        m["metric_id"] for m in alternative["metrics"]
    )
    assert all(
        m["metric_id"].startswith(original["result_id"] + ":")
        for m in original["metrics"]
    )


def test_result_identity_preserves_identifiers_and_periods():
    body = inputs()["pay_bridge"]
    body["person_ref"] = "001"
    first = calculate("pay_bridge", "1", body)
    body["person_ref"] = "1"
    assert calculate("pay_bridge", "1", body)["result_id"] != first["result_id"]
    body = inputs()["cash_ladder"]
    first = calculate("cash_ladder", "1", body)
    body["end_date"] = "2030-02-01"
    assert calculate("cash_ladder", "1", body)["result_id"] != first["result_id"]
